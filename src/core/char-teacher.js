  // 取第一个常用词
  const word = words[0].word;
  const xinhua = loadXinhua();
  const pos = xinhua[hanzi] && xinhua[hanzi].pos ? xinhua[hanzi].pos[0] : '';

  // 动物/食物类名词模板
  const animalWords = ['螃蟹', '蝴蝶', '蜻蜓', '蚂蚁', '蜜蜂', '小鸟', '小鱼', '兔子', '老虎', '狮子', '大象', '猴子', '熊猫', '青蛙', '虫子', '鹦鹉', '鲸鱼', '海豚', '企鹅', '长颈鹿'];
