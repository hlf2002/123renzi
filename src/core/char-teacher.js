/**
 * 句子解读：解释整句话的意思，用儿童能理解的语言。
 * @param {string} hanzi
 * @param {string} sentence
 * @param {string} [pos] 词性
 * @param {string} [meaning] 字义
 * @returns {string}
 */
function getUsage(hanzi, sentence, pos, meaning) {
  if (!sentence) return '';

  // 模板句子的解读（根据模板类型准确生成）
  if (sentence.startsWith('我知道')) {
    const word = sentence.replace('我知道', '');
    return `「${sentence}」是说我了解${word}是什么。`;
  }
  if (sentence.startsWith('我喜欢吃')) {
    const word = sentence.replace('我喜欢吃', '');
    return `「${sentence}」是说我觉得${word}很好吃。`;
  }
  if (sentence.endsWith('真可爱')) {
    const word = sentence.replace('真可爱', '');
    return `「${sentence}」是说${word}很讨人喜欢。`;
  }
  if (sentence.startsWith('这里很')) {
    const word = sentence.replace('这里很', '');
    return `「${sentence}」是说这个地方很${word}。`;
  }
  if (sentence.startsWith('我喜欢') && !sentence.startsWith('我喜欢吃')) {
    const word = sentence.replace('我喜欢', '');
    return `「${sentence}」是说我很喜欢${word}。`;
  }
  if (sentence.startsWith('我看到了')) {
    const word = sentence.replace('我看到了', '');
    return `「${sentence}」是说我看见了${word}。`;
  }

  // 儿童句子库句子：通用解读（句子本身简单，直接说明句意）
  // 不强行替换字义，避免出现"我是小学习，效法生"这种不通顺的情况
  // 去掉末尾句号避免双句号
  const cleanSentence = sentence.replace(/[。.!！?？]+$/, '');
  return `「${cleanSentence}」描述的是：${cleanSentence}。`;
}

/**
 * 生成完整的教学内容。
 * @param {Object} char { hanzi, pinyin }
 * @param {Object} [context] { currentSentence } 当前学习的句子（用于用法说明）
 * @returns {Promise<Object>} { hanzi, pinyin, words, meaning, sentences, usage, speakParts }
 */
async function teach(char, context = {}) {
  const hanzi = char.hanzi;
  const xinhua = loadXinhua();
  // 优先使用新华字典的拼音，其次用字库传入的拼音
  const pinyin = (xinhua[hanzi] && xinhua[hanzi].pinyin) || char.pinyin || '';
  const words = getWords(hanzi, 3);
  const sentences = getSentences(hanzi, 2);

  // currentSentence 只有在是完整句子（长度>1且不等于单字）时才用作造句
  // 避免单字格学习时 currentSentence=单字，导致造句只有一个字
  let currentSentence = context.currentSentence || '';
  if (currentSentence.length <= 1 || currentSentence === hanzi) {
    currentSentence = '';
  }
  const exampleSentence = currentSentence || sentences[0] || '';

  const pos = xinhua[hanzi] && xinhua[hanzi].pos ? xinhua[hanzi].pos : '';

  let meaning = getMeaning(hanzi, pinyin);
  let usage = getUsage(hanzi, exampleSentence, pos, meaning);

  // AI 接口：如果注入了 AI 教学生成器，用 AI 生成更准确的解释和用法
  if (aiTeacher) {
    try {
      const aiResult = await aiTeacher.generate(hanzi, { pinyin, words, sentences, currentSentence: exampleSentence, pos });
      if (aiResult && aiResult.meaning) meaning = aiResult.meaning;
      if (aiResult && aiResult.usage) usage = aiResult.usage;
    } catch (e) {
      // AI 失败，用模板结果
    }
  }

  // 语音朗读的分段文本：只读字、组词、造句正文
  const speakParts = [
    hanzi,
    words.length > 0 ? words.map(w => w.word).join('、') : '',
    exampleSentence || '',
  ].filter(Boolean);

  return {
    hanzi,
    pinyin,
    words,
    meaning,
    sentences,
    usage,
    exampleSentence,
    pos,
    speakParts,
  };
}

